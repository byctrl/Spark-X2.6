"""Minimal Spark-X2.6-4B health-information chatbot.

HER Hack-Astron #7 (Spark-X2.6 Open Source AI for Good Challenge) entry:
an inclusive, plain-language patient-education chatbot for people who
struggle to read or interpret health information.

The script talks to a **locally hosted** Spark-X2.6-4B model through any
OpenAI-compatible server (vLLM / SGLang / llama.cpp / Spark-MLX-LLM):

    # example: serve the model locally, then point the client at it
    export SPARK_BASE_URL=http://127.0.0.1:30000/v1
    python src/health_chatbot.py "I have had a cough and fever for 3 days"

Safety boundary: the model only explains health topics in simple language.
It never diagnoses, never prescribes and always points the user to a
qualified clinician. Output is education, not medical advice.
"""

from __future__ import annotations

import argparse
import json
import os
import urllib.error
import urllib.request
from typing import Callable, Dict, List, Optional

MODEL_ID = "XHToken/Spark-X2.6-4B"
MAX_NEW_TOKENS = 1024
DEFAULT_BASE_URL = "http://127.0.0.1:30000/v1"
REQUEST_TIMEOUT = 120

SYSTEM_PROMPT = (
    "You are a patient-education assistant for a public-interest health "
    "information service. Your readers include people with low health "
    "literacy, disabilities, or limited access to care.\n"
    "Rules:\n"
    "1. Answer in the language the user writes in, in short plain sentences "
    "and everyday words. Define any medical term you have to use.\n"
    "2. Explain what the symptom or topic usually means, which warning signs "
    "need urgent care, and what a person can reasonably do next.\n"
    "3. Never diagnose, never prescribe, never give drug doses, and never "
    "tell the user to stop a treatment. Say clearly that only a qualified "
    "clinician can diagnose or treat.\n"
    "4. If the message suggests an emergency (chest pain, trouble breathing, "
    "heavy bleeding, fainting, thoughts of self-harm, labour or birth "
    "complications), tell the user to contact local emergency services now.\n"
    "5. Do not ask for names, addresses, ID numbers or other personal data; "
    "remind the user not to share them.\n"
    "6. If you are unsure, say so and point to a clinician or community "
    "health worker instead of guessing."
)

DISCLAIMER = (
    "This is general health education generated by Spark-X2.6-4B, not medical "
    "advice. For diagnosis or treatment, contact a qualified clinician. In an "
    "emergency, call your local emergency number."
)

DEMO_QUESTION = (
    "I came back from a trip two weeks ago and now I have a dry cough, a mild "
    "fever and I feel very tired. There is no doctor nearby. What should I pay "
    "attention to?"
)


def build_messages(
    question: str, history: Optional[List[Dict[str, str]]] = None
) -> List[Dict[str, str]]:
    """Build the chat messages sent to Spark-X2.6-4B."""
    question = (question or "").strip()
    if not question:
        raise ValueError("question must not be empty")

    messages: List[Dict[str, str]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    for turn in history or []:
        role = (turn or {}).get("role")
        content = ((turn or {}).get("content") or "").strip()
        if role in ("user", "assistant") and content:
            messages.append({"role": role, "content": content})
    messages.append({"role": "user", "content": question})
    return messages


def build_payload(
    messages: List[Dict[str, str]],
    max_tokens: int = MAX_NEW_TOKENS,
    temperature: float = 0.3,
    model: str = MODEL_ID,
) -> Dict[str, object]:
    """Build an OpenAI-compatible chat-completions payload."""
    return {
        "model": model,
        "messages": messages,
        "max_tokens": max_tokens,
        "temperature": temperature,
        "stream": False,
    }


def extract_reply(data: Dict[str, object]) -> str:
    """Pull the assistant text out of a chat-completions response."""
    try:
        content = data["choices"][0]["message"]["content"]  # type: ignore[index]
    except (KeyError, IndexError, TypeError) as exc:
        raise ValueError("unexpected response shape from Spark endpoint") from exc
    if not isinstance(content, str) or not content.strip():
        raise ValueError("empty reply from Spark endpoint")
    return content.strip()


def http_transport(
    url: str, payload: Dict[str, object], timeout: int = REQUEST_TIMEOUT
) -> Dict[str, object]:
    """POST JSON to an OpenAI-compatible endpoint (stdlib only)."""
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        raw = response.read().decode("utf-8")
    return json.loads(raw)


def chat(
    question: str,
    base_url: Optional[str] = None,
    history: Optional[List[Dict[str, str]]] = None,
    transport: Callable[[str, Dict[str, object]], Dict[str, object]] = http_transport,
    max_tokens: int = MAX_NEW_TOKENS,
    model: str = MODEL_ID,
) -> str:
    """Ask the locally hosted Spark-X2.6-4B model a health question."""
    resolved = (
        base_url or os.environ.get("SPARK_BASE_URL") or DEFAULT_BASE_URL
    ).rstrip("/")
    messages = build_messages(question, history)
    payload = build_payload(messages, max_tokens=max_tokens, model=model)

    try:
        data = transport(resolved + "/chat/completions", payload)
    except (urllib.error.URLError, OSError, ValueError) as exc:
        raise RuntimeError(
            "Spark-X2.6 request failed (%s). Is a local OpenAI-compatible "
            "server for %s running?" % (exc, MODEL_ID)
        ) from exc
    return extract_reply(data)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Spark-X2.6-4B plain-language health-information chatbot"
    )
    parser.add_argument(
        "question",
        nargs="*",
        help="question to ask; defaults to the built-in demo question",
    )
    parser.add_argument(
        "--base-url",
        default=None,
        help="OpenAI-compatible Spark endpoint (default: $SPARK_BASE_URL or "
        + DEFAULT_BASE_URL
        + ")",
    )
    parser.add_argument(
        "--show-messages",
        action="store_true",
        help="print the prompt that will be sent to the model",
    )
    args = parser.parse_args(argv)

    question = " ".join(args.question).strip() or DEMO_QUESTION
    if args.show_messages:
        print(json.dumps(build_messages(question), indent=2, ensure_ascii=False))

    try:
        reply = chat(question, base_url=args.base_url)
    except RuntimeError as exc:
        print("Error: %s" % exc)
        print(
            "Serve Spark-X2.6-4B locally with an OpenAI-compatible server and set "
            "SPARK_BASE_URL (see module docstring)."
        )
        return 1

    print(reply)
    print()
    print(DISCLAIMER)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
